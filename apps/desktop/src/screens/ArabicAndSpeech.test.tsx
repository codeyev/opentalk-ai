import { act, fireEvent, screen, within } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { fakeCapture, fakeCaptureClientModule } from "../test/fakeCapture";
import { fakeProvider, fakeProviderClientModule } from "../test/fakeProvider";
import { installFakeSpeech } from "../test/fakeSpeech";
import { renderApp } from "../test/renderApp";

vi.mock("../capture/captureClient", () => fakeCaptureClientModule());
vi.mock("../providers/providerClient", () => fakeProviderClientModule());

function open(screenName: string) {
  fireEvent.click(screen.getByRole("button", { name: screenName }));
}

describe("Arabic output settings", () => {
  beforeEach(() => {
    fakeCapture.reset();
    fakeProvider.reset();
  });

  it("offers a dialect only when a provider accepts one", async () => {
    fakeProvider.status = null;
    renderApp();
    open("Languages");
    expect(screen.getByRole("radio", { name: "Dialect" })).toBeDisabled();
    expect(screen.getByRole("radio", { name: "Modern Standard Arabic" })).toBeChecked();
    expect(await screen.findByText(/A dialect can be chosen once a provider/)).toBeInTheDocument();
  });

  it("warns that dialect output is unverified when one is chosen", async () => {
    renderApp();
    open("Languages");
    const dialect = screen.getByRole("radio", { name: "Dialect" });
    await vi.waitFor(() => {
      expect(dialect).toBeEnabled();
    });
    fireEvent.click(dialect);
    expect(screen.getByLabelText("Dialect name")).toBeInTheDocument();
    expect(screen.getByText(/has not been verified/)).toBeInTheDocument();
  });

  it("sends the chosen dialect and tashkeel level with a session", async () => {
    fakeProvider.reset({ hasApiKey: true });
    renderApp();
    open("Languages");
    const dialect = screen.getByRole("radio", { name: "Dialect" });
    await vi.waitFor(() => {
      expect(dialect).toBeEnabled();
    });
    fireEvent.click(dialect);
    fireEvent.change(screen.getByLabelText("Dialect name"), { target: { value: " Egyptian " } });
    fireEvent.click(screen.getByRole("radio", { name: "Full" }));

    open("Providers");
    fireEvent.click(
      await screen.findByRole("checkbox", { name: /Send captured speech to OpenAI/ }),
    );
    fireEvent.click(screen.getByRole("checkbox", { name: /Send transcript text to OpenAI/ }));
    open("Live workspace");
    await screen.findByText(/Translation into English is on/);
    fireEvent.click(screen.getByRole("button", { name: "Start" }));
    await screen.findByText("Capturing audio");

    expect(fakeCapture.startCapture).toHaveBeenCalledWith(
      expect.anything(),
      expect.objectContaining({
        translation: expect.objectContaining({
          arabic: { dialect: "Egyptian", tashkeel: "full" },
        }) as unknown,
      }),
    );
  });

  it("explains that diacritics are removed when tashkeel is off, and can be wrong otherwise", () => {
    renderApp();
    open("Languages");
    expect(
      screen.getByText(/With tashkeel off, diacritics are always removed/),
    ).toBeInTheDocument();
    expect(screen.getByText(/generated by a model and can be wrong/)).toBeInTheDocument();
  });
});

describe("Speech output", () => {
  const suggestion = {
    style: "concise" as const,
    text: "Understood.",
    meaning: null,
    asksForMissingFacts: false,
  };

  beforeEach(() => {
    fakeCapture.reset();
    fakeProvider.reset({ hasApiKey: true });
  });

  afterEach(() => {
    vi.unstubAllGlobals();
  });

  /** Turns on transcription and replies, and speech if asked, then shows one suggestion. */
  async function showSuggestion({ withSpeech }: { withSpeech: boolean }) {
    renderApp();
    open("Providers");
    fireEvent.click(
      await screen.findByRole("checkbox", { name: /Send captured speech to OpenAI/ }),
    );
    fireEvent.click(screen.getByRole("checkbox", { name: /Send the conversation to OpenAI/ }));
    if (withSpeech) {
      fireEvent.click(screen.getByRole("checkbox", { name: /Show a Speak button/ }));
    }
    open("Live workspace");
    await screen.findByText(/Reply suggestions are on/);
    fireEvent.click(screen.getByRole("button", { name: "Start" }));
    await screen.findByText("Capturing audio");
    act(() => {
      fakeCapture.events().onReplies({ status: "ready", suggestions: [suggestion] });
    });
    return screen.getByRole("region", { name: /^Reply suggestions/ });
  }

  it("cannot be turned on where the system has no speech output", () => {
    renderApp();
    open("Providers");
    expect(screen.getByRole("checkbox", { name: /Show a Speak button/ })).toBeDisabled();
    expect(screen.getByText(/does not offer speech output/)).toBeInTheDocument();
  });

  it("is off by default even where it is available", async () => {
    installFakeSpeech(["en-US"]);
    const replies = await showSuggestion({ withSpeech: false });
    expect(within(replies).queryByRole("button", { name: /Speak/ })).not.toBeInTheDocument();
  });

  it("speaks a reply only when the user presses Speak", async () => {
    const speech = installFakeSpeech(["en-US"]);
    const replies = await showSuggestion({ withSpeech: true });
    expect(speech.speak).not.toHaveBeenCalled();

    fireEvent.click(within(replies).getByRole("button", { name: "Speak the Concise reply" }));
    expect(speech.speak).toHaveBeenCalledOnce();
    expect(speech.speak.mock.calls[0]?.[0].text).toBe("Understood.");
  });

  it("disables Speak when no voice is installed for the reply language", async () => {
    installFakeSpeech(["ar-SA"]);
    const replies = await showSuggestion({ withSpeech: true });
    const speak = within(replies).getByRole("button", { name: "Speak the Concise reply" });
    expect(speak).toBeDisabled();
    expect(speak).toHaveAttribute("title", "No system voice is installed for this language.");
  });
});
